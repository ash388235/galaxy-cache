#!/usr/bin/env bash
# A 3-node grid in Docker on one machine: three node containers (grid1, grid2, grid3) on their own network, a dashboard,
# and client containers. It mimics separate Linux hosts: real host names, token authentication and TLS, data on
# separate volumes, fail-stop. Made for WSL2 (docs/WSL-LOCAL-LINUX.md) but works on any Linux with Docker.
#
#   scripts/docker-grid.sh up [--no-tls]        create secrets and config (first time), build the image, start nodes + dashboard
#   scripts/docker-grid.sh status               node health (READY / FORMING) through the published admin ports
#   scripts/docker-grid.sh demo [total] [writers]   writers + a reader, each in its own client container (default 100000 2)
#   scripts/docker-grid.sh client <main-class> [args...]   run any class from galaxy-examples.jar in a client container
#   scripts/docker-grid.sh kill <node-1|node-2|node-3>      kill one node to watch fail-stop
#   scripts/docker-grid.sh logs <node-1|node-2|node-3|dashboard>
#   scripts/docker-grid.sh restart              stop and start every node (the fail-stop recovery)
#   scripts/docker-grid.sh down                 remove the containers; data, secrets and config are kept
#   scripts/docker-grid.sh clean                down, then delete the data volumes, the network, secrets and config
#
# Environment: GALAXY_HEAP (node heap, default 1g), GALAXY_CLIENT_HEAP (default 2g),
#              GALAXY_BASE_IMAGE (default eclipse-temurin:21-jre; multi-arch, so ARM machines run natively),
#              GALAXY_NOFILE (open-file limit per node, default 65536; set it empty to keep Docker's default).
# Published on 127.0.0.1 only: dashboard 8080, node admin ports 7201-7203. The grid protocol port 7101 stays inside
# the Docker network, as it would behind a firewall.
set -euo pipefail
source "$(dirname "$0")/common.sh"
here="$(cd "$(dirname "$0")" && pwd)"

STATE="$ROOT/galaxy-data/docker"          # galaxy-data/ is git-ignored
SECRETS="$STATE/secrets"
NET=galaxy-net
IMAGE=galaxy-grid-node
BASE_IMAGE="${GALAXY_BASE_IMAGE:-eclipse-temurin:21-jre}"
NODE_HEAP="${GALAXY_HEAP:-1g}"
CLIENT_HEAP="${GALAXY_CLIENT_HEAP:-2g}"
NOFILE="${GALAXY_NOFILE-65536}"
NODES=(node-1 node-2 node-3)
EXAMPLES_JAR="$ROOT/galaxy-examples/target/galaxy-examples.jar"
DASHBOARD_JAR="$ROOT/galaxy-dashboard/target/galaxy-dashboard.jar"
NODE_JAR="$ROOT/galaxy-grid-node/target/galaxy-grid-node.jar"

host_of() { echo "grid${1#node-}"; }               # node-1 -> grid1
container_of() { echo "galaxy-$(host_of "$1")"; }  # node-1 -> galaxy-grid1
admin_port_of() { echo "$((7200 + ${1#node-}))"; } # node-1 -> 7201

need_docker() {
  command -v docker >/dev/null || { echo "docker is not installed; see docs/WSL-LOCAL-LINUX.md" >&2; exit 1; }
  docker info >/dev/null 2>&1 || { echo "cannot reach the Docker daemon: is it running, and are you in the docker group?" >&2; exit 1; }
}

# Writes the node and client configs from deploy/galaxy-cluster.yaml.example, so they track the production example.
write_configs() {
  local tls="$1" example="$ROOT/deploy/galaxy-cluster.yaml.example"
  mkdir -p "$STATE/config"
  { echo "# Generated by scripts/docker-grid.sh from deploy/galaxy-cluster.yaml.example; changes here are overwritten."
  sed -e 's/^cluster: .*/cluster: docker-grid/' \
      -e 's/grid\([0-9]\)\.example\.com/grid\1/g' \
      -e 's#/var/lib/galaxy/catalog#/var/lib/galaxy-shared/catalog#' \
      -e 's#/var/log/galaxy/query#/var/lib/galaxy-shared/query#' \
      -e 's/^\(    tls: true.*\)$/\1\n    bindAddress: 0.0.0.0              # containers: listen on the container address/' \
      "$example"; } >"$STATE/config/node.yaml"
  if ! grep -q 'bindAddress: 0.0.0.0' "$STATE/config/node.yaml"; then
    echo "could not add bindAddress to the config: has $example changed?" >&2
    exit 1
  fi
  if [ "$tls" = off ]; then
    sed -i -e '/^    tls/d' "$STATE/config/node.yaml"
  fi
  # clients only need the truststore (and the dashboard is a client)
  sed -e '/tlsKeyStore/d' "$STATE/config/node.yaml" >"$STATE/config/client.yaml"
  echo "$tls" >"$STATE/tls-mode"
}

setup() {
  local tls="$1"
  if [ ! -f "$SECRETS/grid.env" ]; then
    echo "creating token and certificates in $SECRETS"
    "$here/generate-grid-secrets.sh" "$SECRETS" node-1=grid1 node-2=grid2 node-3=grid3
  fi
  if [ ! -f "$STATE/tls-mode" ] || [ "$(cat "$STATE/tls-mode")" != "$tls" ] || [ ! -f "$STATE/config/node.yaml" ]; then
    write_configs "$tls"
  fi
  # the containers run as root and read these through bind mounts; keep them private to you on this machine
  chmod 700 "$STATE" "$SECRETS"
}

build_image() {
  echo "building image $IMAGE from deploy/Dockerfile.grid-node (base $BASE_IMAGE)"
  # The Dockerfile names eclipse-temurin:21-jre; GALAXY_BASE_IMAGE lets a mirror stand in for it.
  if [ "$BASE_IMAGE" != "eclipse-temurin:21-jre" ]; then
    docker image inspect eclipse-temurin:21-jre >/dev/null 2>&1 || {
      docker pull "$BASE_IMAGE" && docker tag "$BASE_IMAGE" eclipse-temurin:21-jre
    }
  fi
  docker build -q -f "$ROOT/deploy/Dockerfile.grid-node" -t "$IMAGE" "$ROOT" >/dev/null
}

running() { [ "$(docker inspect -f '{{.State.Running}}' "$1" 2>/dev/null)" = true ]; }
exists() { docker inspect "$1" >/dev/null 2>&1; }

start_node() {
  local node="$1" c
  c="$(container_of "$node")"
  exists "$c" && docker rm -f "$c" >/dev/null
  local limits=()
  [ -n "$NOFILE" ] && limits=(--ulimit "nofile=$NOFILE:$NOFILE")
  # --restart no: under fail-stop a node that stopped must not rejoin by itself
  docker run -d --name "$c" --hostname "$(host_of "$node")" --network "$NET" --network-alias "$(host_of "$node")" \
    --restart no "${limits[@]}" \
    --env-file "$SECRETS/grid.env" -e GALAXY_NODE="$node" -e GALAXY_HEAP="$NODE_HEAP" \
    -v "$STATE/config/node.yaml:/etc/galaxy/galaxy.yaml:ro" \
    -v "$SECRETS/nodes/$node.p12:/etc/galaxy/tls/node.p12:ro" \
    -v "$SECRETS/truststore.p12:/etc/galaxy/tls/truststore.p12:ro" \
    -v "galaxy-$(host_of "$node")-data:/var/lib/galaxy" \
    -v galaxy-shared:/var/lib/galaxy-shared \
    -p "127.0.0.1:$(admin_port_of "$node"):7201" \
    "$IMAGE" >/dev/null
  echo "$node started as container $c (host $(host_of "$node"))"
}

start_dashboard() {
  exists galaxy-dashboard && docker rm -f galaxy-dashboard >/dev/null
  # inside the container it listens on all addresses; Docker publishes it on this machine's 127.0.0.1 only
  docker run -d --name galaxy-dashboard --hostname dashboard --network "$NET" --restart no \
    --env-file "$SECRETS/grid.env" \
    -v "$STATE/config/client.yaml:/etc/galaxy/galaxy.yaml:ro" \
    -v "$SECRETS/truststore.p12:/etc/galaxy/tls/truststore.p12:ro" \
    -v "$DASHBOARD_JAR:/opt/galaxy/lib/galaxy-dashboard.jar:ro" \
    -v galaxy-shared:/var/lib/galaxy-shared \
    -p 127.0.0.1:8080:8080 \
    --entrypoint java "$IMAGE" -Xmx1g -jar /opt/galaxy/lib/galaxy-dashboard.jar \
    --config /etc/galaxy/galaxy.yaml --port 8080 --bind 0.0.0.0 >/dev/null
  echo "dashboard started: http://localhost:8080/?namespace=grid"
}

status() {
  local args=() node
  for node in "${NODES[@]}"; do args+=("127.0.0.1:$(admin_port_of "$node")"); done
  "$here/grid-status.sh" "${args[@]}"
}

await_ready() {
  local node
  for _ in $(seq 1 240); do
    for node in "${NODES[@]}"; do
      if ! running "$(container_of "$node")"; then
        echo "$node exited during startup:" >&2
        docker logs --tail 20 "$(container_of "$node")" >&2
        exit 1
      fi
    done
    if status >/dev/null 2>&1; then
      status
      echo "grid READY"
      return 0
    fi
    sleep 0.5
  done
  status || true
  echo "grid did not become READY; see: scripts/docker-grid.sh logs node-1" >&2
  exit 1
}

up() {
  local tls=on
  [ "${1:-}" = "--no-tls" ] && tls=off
  need_docker
  require_jar "$NODE_JAR"; require_jar "$DASHBOARD_JAR"; require_jar "$EXAMPLES_JAR"
  setup "$tls"
  build_image
  docker network inspect "$NET" >/dev/null 2>&1 || docker network create "$NET" >/dev/null
  # all nodes start together: each waits for its peers (startupWaitMs)
  for node in "${NODES[@]}"; do start_node "$node"; done
  await_ready
  start_dashboard
}

# client <container-name> <client-name> <main-class> [args...]; runs in the foreground, removed when it ends
run_client() {
  local cname="$1" name="$2" main="$3"
  shift 3
  docker run --rm --name "$cname" --network "$NET" \
    --env-file "$SECRETS/grid.env" \
    -v "$STATE/config/client.yaml:/etc/galaxy/galaxy.yaml:ro" \
    -v "$SECRETS/truststore.p12:/etc/galaxy/tls/truststore.p12:ro" \
    -v "$EXAMPLES_JAR:/opt/galaxy/lib/galaxy-examples.jar:ro" \
    -v galaxy-shared:/var/lib/galaxy-shared \
    --entrypoint java "$IMAGE" "-Xmx$CLIENT_HEAP" "-Dgalaxy.client.name=$name" \
    -cp /opt/galaxy/lib/galaxy-examples.jar "$main" "$@"
}

demo() {
  local total="${1:-100000}" writers="${2:-2}" main=io.galaxycache.examples.sizing.GridDemo
  need_docker
  status >/dev/null 2>&1 || { echo "grid is not READY; run: scripts/docker-grid.sh up" >&2; exit 1; }
  mkdir -p "$STATE/logs"
  run_client galaxy-client-reset reset "$main" --config /etc/galaxy/galaxy.yaml --reset >"$STATE/logs/demo-reset.log" 2>&1
  local pids=() w failed=0
  run_client galaxy-client-reader reader "$main" --config /etc/galaxy/galaxy.yaml \
    --read --writers "$writers" --total "$total" >"$STATE/logs/demo-reader.log" 2>&1 &
  pids+=("$!")
  echo "reader started (container galaxy-client-reader)"
  for w in $(seq 1 "$writers"); do
    run_client "galaxy-client-writer-$w" "writer-$w" "$main" --config /etc/galaxy/galaxy.yaml \
      --write "$w" --writers "$writers" --total "$total" >"$STATE/logs/demo-writer-$w.log" 2>&1 &
    pids+=("$!")
    echo "writer-$w started (container galaxy-client-writer-$w)"
  done
  echo "Dashboard: http://localhost:8080/?namespace=grid"
  for pid in "${pids[@]}"; do wait "$pid" || failed=1; done
  echo
  grep -h DONE "$STATE"/logs/demo-writer-*.log || true
  grep -h 'reader:' "$STATE/logs/demo-reader.log" || true
  if [ "$failed" -ne 0 ]; then
    echo "a client failed; see $STATE/logs/demo-*.log" >&2
    exit 1
  fi
}

down() {
  local c
  for c in galaxy-dashboard $(docker ps -a --format '{{.Names}}' | grep '^galaxy-client-' || true) \
           "$(container_of node-1)" "$(container_of node-2)" "$(container_of node-3)"; do
    exists "$c" && docker rm -f "$c" >/dev/null && echo "removed $c"
  done
  return 0
}

case "${1:-}" in
  up) shift; up "$@" ;;
  status) status ;;
  demo) shift; demo "$@" ;;
  client)
    shift
    [ "$#" -ge 1 ] || { echo "usage: docker-grid.sh client <main-class> [args...]" >&2; exit 2; }
    need_docker
    main="$1"; shift
    run_client "galaxy-client-$$" "client-$$" "$main" "$@"
    ;;
  kill)
    node="${2:?usage: docker-grid.sh kill node-1|node-2|node-3}"
    docker kill "$(container_of "$node")" >/dev/null && echo "killed $node; the other nodes stop themselves within about 5 s (fail-stop)"
    ;;
  logs)
    what="${2:?usage: docker-grid.sh logs node-1|node-2|node-3|dashboard}"
    if [ "$what" = dashboard ]; then docker logs galaxy-dashboard; else docker logs "$(container_of "$what")"; fi
    ;;
  restart)
    need_docker
    tls="$(cat "$STATE/tls-mode" 2>/dev/null || echo on)"
    down
    if [ "$tls" = off ]; then up --no-tls; else up; fi
    ;;
  down) need_docker; down ;;
  clean)
    need_docker
    down
    docker volume rm galaxy-grid1-data galaxy-grid2-data galaxy-grid3-data galaxy-shared >/dev/null 2>&1 || true
    docker network rm "$NET" >/dev/null 2>&1 || true
    rm -rf "$STATE"
    echo "removed the data volumes, the network, and $STATE"
    ;;
  *)
    sed -n '2,20p' "$0" | sed 's/^# \{0,1\}//'
    exit 2
    ;;
esac
